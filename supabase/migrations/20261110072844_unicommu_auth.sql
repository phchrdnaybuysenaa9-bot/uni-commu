CREATE SCHEMA unicommu;
REVOKE ALL ON SCHEMA unicommu FROM PUBLIC;

CREATE TABLE unicommu.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email varchar(254) NOT NULL CONSTRAINT uq_users_email UNIQUE,
  display_name varchar(100) NOT NULL,
  password_hash varchar(255) NOT NULL,
  role varchar(10) NOT NULL DEFAULT 'student' CHECK (role IN ('student', 'department', 'admin')),
  email_verified_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  email_verification_token_hash bytea CONSTRAINT uq_users_verification_token UNIQUE
    CHECK (octet_length(email_verification_token_hash) = 32),
  email_verification_expires_at timestamptz,
  email_verification_challenge_hash bytea CONSTRAINT uq_users_verification_challenge UNIQUE
    CHECK (octet_length(email_verification_challenge_hash) = 32),
  email_verification_attempts smallint NOT NULL DEFAULT 0 CHECK (email_verification_attempts BETWEEN 0 AND 255)
);

CREATE TABLE unicommu.sessions (
  token_hash bytea PRIMARY KEY CHECK (octet_length(token_hash) = 32),
  user_id bigint NOT NULL REFERENCES unicommu.users (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at timestamptz NOT NULL
);

CREATE INDEX idx_sessions_user_id ON unicommu.sessions (user_id);
CREATE INDEX idx_sessions_expires_at ON unicommu.sessions (expires_at);

ALTER TABLE unicommu.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE unicommu.sessions ENABLE ROW LEVEL SECURITY;
