const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const tokens = require(path.join(root, 'src/constants/design-tokens.json'));
const kebab = value => value.replace(/[A-Z]/g, char => '-' + char.toLowerCase());
const lines = Object.entries(tokens).flatMap(([group, values]) =>
  Object.entries(values).map(([key, value]) => {
    const unit = typeof value === 'number' && group !== 'opacity' ? 'px' : '';
    return '  --' + kebab(group) + '-' + kebab(key) + ': ' + value + unit + ';';
  })
);
const css = '/* Generated by npm run theme:generate. Edit src/constants/design-tokens.json. */\n:root {\n' + lines.join('\n') + '\n}\n';
const target = path.join(root, 'src/design-tokens.css');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== css) {
    console.error('Theme CSS is out of date. Run npm run theme:generate.');
    process.exitCode = 1;
  }
} else fs.writeFileSync(target, css);
